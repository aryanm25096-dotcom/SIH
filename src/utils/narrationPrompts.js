/**
 * Gets localized prompt for screen narration, falling back to English or custom text.
 */
export function getLocalizedPrompt(screenKey, lang = 'en', fallbackText = '') {
  const group = screenNarrationPrompts[screenKey];
  if (group && group[lang]) {
    return group[lang];
  }
  if (group && group.en) {
    return group.en;
  }
  return fallbackText;
}
